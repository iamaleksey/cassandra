public class MarkShardsSealedTest
{
    private static final AtomicInteger counter = new AtomicInteger();

    private static Location local;
    private static String ks;

    @BeforeClass
    public static void setUpClass() throws Exception
    {
        CassandraRelevantProperties.PARTITIONER.setString(Murmur3Partitioner.class.getName());
        ServerTestUtils.daemonInitialization();
        ServerTestUtils.prepareServer();
        MutationJournal.start();

        ClusterMetadata metadata = ClusterMetadata.current();
        local = metadata.directory.location(metadata.myNodeId());
        long[] tokens = { -6_000_000_000_000_000_000L, -2_000_000_000_000_000_000L, 2_000_000_000_000_000_000L, 6_000_000_000_000_000_000L };
        for (int i = 0; i < tokens.length; i++)
            ClusterMetadataTestHelper.addEndpoint(InetAddressAndPort.getByName("127.0.0." + (i + 2)), token(tokens[i]), local);
    }

    @After
    public void tearDown() throws Exception
    {
        for (MultiStepOperation.SequenceKey key : ClusterMetadata.current().inProgressSequences.keys())
            if (key instanceof NodeId)
                commit(new CancelInProgressSequence((NodeId) key));
        if (ks != null)
            schemaChange("DROP KEYSPACE IF EXISTS " + ks);
        ks = null;
    }

    @Test
    public void marksSealingShardsSealed() throws Exception
    {
        ClusterMetadata before = startJoin();
        Map<ShardKey, ShardValue> prior = shards(before);
        Set<ShardKey> sealing = keysIn(prior, State.SEALING);
        assertFalse(sealing.isEmpty());

        ClusterMetadata after = commit(new MarkShardsSealed(ImmutableMap.of(ks, sealing)));
        Map<ShardKey, ShardValue> current = shards(after);

        assertEquals(prior.keySet(), current.keySet());
        prior.forEach((key, value) -> {
            ShardValue sealed = current.get(key);
            if (sealing.contains(key))
            {
                assertEquals(State.SEALED, sealed.state);
                assertEquals("sealing epoch should be retained", value.sealingEpoch, sealed.sealingEpoch);
                assertEquals("sealed epoch should be the epoch of the transformation", after.epoch.getEpoch(), sealed.sealedEpoch);
                assertEquals(value.participants, sealed.participants);
            }
            else
            {
                assertEquals(value, sealed);
            }
        });

        assertTrue(MetadataKeys.diffKeys(before, after).contains(MetadataKeys.MUTATION_TRACKING_SHARDS));
        assertEquals(after.epoch, after.mutationTrackingShards.lastModified);
        for (ShardValue value : current.values())
            if (value.state == State.SEALED)
                assertTrue(after.mutationTrackingShards.markedSealingAt(Epoch.create(value.sealingEpoch)).isEmpty());
    }

    @Test
    public void isIdempotent() throws Exception
    {
        ClusterMetadata before = startJoin();
        MarkShardsSealed mark = new MarkShardsSealed(ImmutableMap.of(ks, keysIn(shards(before), State.SEALING)));

        ClusterMetadata first = commit(mark);
        Transformation.Result second = mark.execute(first);
        assertTrue(second.isSuccess());
        assertSame("re-sealing should not move the sealed epoch", first.mutationTrackingShards, second.success().metadata.mutationTrackingShards);
    }

    @Test
    public void rejectsActiveShards() throws Exception
    {
        ClusterMetadata before = startJoin();
        Map<ShardKey, ShardValue> shards = shards(before);
        Set<ShardKey> keys = new HashSet<>(keysIn(shards, State.SEALING));
        keys.add(keysIn(shards, State.ACTIVE).iterator().next());

        Transformation.Result result = new MarkShardsSealed(ImmutableMap.of(ks, keys)).execute(before);
        assertFalse(result.isSuccess());
        assertTrue(result.rejected().reason, result.rejected().reason.contains("ACTIVE"));
    }

    @Test
    public void skipsUnknownKeyspacesAndShards() throws Exception
    {
        ClusterMetadata before = startJoin();
        ShardKey unknown = new ShardKey(new Range<>(token(1), token(2)), 1);
        Transformation.Result result = new MarkShardsSealed(ImmutableMap.of("unknown_ks", ImmutableSet.of(unknown), ks, ImmutableSet.of(unknown)))
                                       .execute(before);
        assertTrue(result.isSuccess());
        assertSame(before.mutationTrackingShards, result.success().metadata.mutationTrackingShards);
    }

    @Test
    public void untrackingKeyspaceOnlyDisablesActiveShards() throws Exception
    {
        ClusterMetadata cancelled = cancelledJoin();
        Set<ShardKey> sealing = keysIn(shards(cancelled), State.SEALING);
        ShardKey toSeal = sealing.iterator().next();
        ClusterMetadata before = commit(new MarkShardsSealed(ImmutableMap.of(ks, ImmutableSet.of(toSeal))));
        Map<ShardKey, ShardValue> prior = shards(before);

        ClusterMetadata after = schemaChangeAndGet("ALTER KEYSPACE " + ks + " WITH replication_type = 'untracked'");
        Map<ShardKey, ShardValue> current = shards(after);

        assertEquals(prior.keySet(), current.keySet());
        assertEquals(State.SEALED, current.get(toSeal).state);
        prior.forEach((key, value) -> {
            if (value.state == State.ACTIVE)
            {
                assertEquals(State.DISABLED, current.get(key).state);
                assertEquals(value.participants, current.get(key).participants);
            }
            else
            {
                assertEquals("SEALING and SEALED shards should be left as they are", value, current.get(key));
            }
        });
    }

    @Test
    public void skipsDisabledShards() throws Exception
    {
        cancelledJoin();
        ClusterMetadata untracked = schemaChangeAndGet("ALTER KEYSPACE " + ks + " WITH replication_type = 'untracked'");
        Set<ShardKey> disabled = keysIn(shards(untracked), State.DISABLED);
        assertFalse(disabled.isEmpty());

        Transformation.Result result = new MarkShardsSealed(ImmutableMap.of(ks, disabled)).execute(untracked);
        assertTrue(result.isSuccess());
        assertSame(untracked.mutationTrackingShards, result.success().metadata.mutationTrackingShards);
    }

    @Test
    public void serializationRoundTrip() throws Exception
    {
        ClusterMetadata before = startJoin();
        MarkShardsSealed mark = new MarkShardsSealed(ImmutableMap.of(ks, keysIn(shards(before), State.SEALING),
                                                                     "other_ks", ImmutableSet.of(new ShardKey(new Range<>(token(0), token(Long.MIN_VALUE)), 7))));
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            MarkShardsSealed.serializer.serialize(mark, out, NodeVersion.CURRENT_METADATA_VERSION);
            assertEquals(MarkShardsSealed.serializer.serializedSize(mark, NodeVersion.CURRENT_METADATA_VERSION), out.getLength());
            try (DataInputBuffer in = new DataInputBuffer(out.toByteArray()))
            {
                assertEquals(mark, MarkShardsSealed.serializer.deserialize(in, NodeVersion.CURRENT_METADATA_VERSION));
                assertEquals(0, in.available());
            }
        }
    }

    private static ClusterMetadata startJoin() throws Exception
    {
        ks = "ks_mark_sealed_" + counter.incrementAndGet();
        schemaChange("CREATE KEYSPACE " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '3'} AND replication_type = 'tracked'");

        NodeId joining = ClusterMetadataTestHelper.register(InetAddressAndPort.getByName("127.0.1." + counter.incrementAndGet()), local.datacenter, local.rack);
        commit(new PrepareJoin(joining, ImmutableSet.of(token(counter.incrementAndGet() * 1_000_000_000_000_000L)),
                               ClusterMetadataService.instance().placementProvider(), true, false));
        BootstrapAndJoin plan = (BootstrapAndJoin) ClusterMetadata.current().inProgressSequences.get(joining);
        return commit(plan.startJoin);
    }

    /**
     * A join cancelled after START_JOIN, which leaves SEALING shards behind; schema changes are refused while it's in progress.
     */
    private static ClusterMetadata cancelledJoin() throws Exception
    {
        startJoin();
        NodeId joining = null;
        for (MultiStepOperation.SequenceKey key : ClusterMetadata.current().inProgressSequences.keys())
            if (key instanceof NodeId)
                joining = (NodeId) key;
        assertNotNull(joining);
        return commit(new CancelInProgressSequence(joining));
    }

    private static ClusterMetadata schemaChangeAndGet(String statement)
    {
        schemaChange(statement);
        return ClusterMetadata.current();
    }

    private static Map<ShardKey, ShardValue> shards(ClusterMetadata metadata)
    {
        Map<ShardKey, ShardValue> shards = metadata.mutationTrackingShards.keyspaces.get(ks);
        assertNotNull(shards);
        return shards;
    }

    private static Set<ShardKey> keysIn(Map<ShardKey, ShardValue> shards, State state)
    {
        Set<ShardKey> keys = new HashSet<>();
        shards.forEach((key, value) -> {
            if (value.state == state)
                keys.add(key);
        });
        return keys;
    }

    private static Token token(long token)
    {
        return new Murmur3Partitioner.LongToken(token);
    }
}
