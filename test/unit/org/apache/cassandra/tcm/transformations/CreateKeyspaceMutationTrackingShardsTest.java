package org.apache.cassandra.tcm.transformations;

import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.atomic.AtomicInteger;

import org.junit.BeforeClass;
import org.junit.Test;

import org.apache.cassandra.ServerTestUtils;
import org.apache.cassandra.config.CassandraRelevantProperties;
import org.apache.cassandra.dht.Murmur3Partitioner;
import org.apache.cassandra.locator.InetAddressAndPort;
import org.apache.cassandra.replication.MutationJournal;
import org.apache.cassandra.replication.MutationTrackingShards.ShardKey;
import org.apache.cassandra.replication.MutationTrackingShards.ShardValue;
import org.apache.cassandra.schema.KeyspaceMetadata;
import org.apache.cassandra.tcm.ClusterMetadata;
import org.apache.cassandra.tcm.ownership.ReplicaGroups;

import static org.apache.cassandra.cql3.CQLTester.schemaChange;
import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertSame;

/**
 * Test generated by an LLM and only skimmed by me (AY).
 * Feel free to get rid of them / rewrite them if they get in the way.
 */
public class CreateKeyspaceMutationTrackingShardsTest
{
    private static final AtomicInteger ksCounter = new AtomicInteger();

    @BeforeClass
    public static void setUpClass() throws Exception
    {
        CassandraRelevantProperties.PARTITIONER.setString(Murmur3Partitioner.class.getName());
        ServerTestUtils.daemonInitialization();
        ServerTestUtils.prepareServer();
        MutationJournal.start();
    }

    private static String createKeyspace(String replicationType)
    {
        String ks = "ks_shards_" + ksCounter.incrementAndGet();
        schemaChange("CREATE KEYSPACE " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '3'} " +
                     "AND replication_type = '" + replicationType + "'");
        return ks;
    }

    private static void assertShardsMatchPlacement(ClusterMetadata metadata, String ks, long expectedEpoch)
    {
        KeyspaceMetadata ksm = metadata.schema.getKeyspaceMetadata(ks);
        ReplicaGroups writes = metadata.placements.get(ksm.params.replication).writes;
        Map<ShardKey, ShardValue> shards = metadata.mutationTrackingShards.keyspaces.get(ks);
        assertNotNull(shards);
        assertEquals(writes.ranges.size(), shards.size());
        for (int i = 0; i < writes.ranges.size(); i++)
        {
            ShardValue shard = shards.get(new ShardKey(writes.ranges.get(i), expectedEpoch));
            assertNotNull("no shard for " + writes.ranges.get(i) + " at epoch " + expectedEpoch, shard);

            Set<Integer> expected = new HashSet<>();
            for (InetAddressAndPort endpoint : writes.endpoints.get(i).endpoints())
                expected.add(metadata.directory.peerId(endpoint).id());
            assertEquals(expected, shard.participants.asSet());
        }
    }

    @Test
    public void trackedKeyspaceGetsShardsAtCreationEpoch()
    {
        String ks = createKeyspace("tracked");
        ClusterMetadata metadata = ClusterMetadata.current();
        assertShardsMatchPlacement(metadata, ks, metadata.epoch.getEpoch());
    }

    @Test
    public void untrackedKeyspaceGetsNoShards()
    {
        String ks = createKeyspace("untracked");
        assertFalse(ClusterMetadata.current().mutationTrackingShards.keyspaces.containsKey(ks));
    }

    @Test
    public void keyspaceSharingPlacementGetsItsOwnEpoch()
    {
        String first = createKeyspace("tracked");
        long firstEpoch = ClusterMetadata.current().epoch.getEpoch();
        String second = createKeyspace("tracked");

        ClusterMetadata metadata = ClusterMetadata.current();
        assertShardsMatchPlacement(metadata, first, firstEpoch);
        assertShardsMatchPlacement(metadata, second, metadata.epoch.getEpoch());
    }

    @Test
    public void createIfNotExistsOnExistingKeyspaceKeepsShards()
    {
        String ks = createKeyspace("tracked");
        ClusterMetadata before = ClusterMetadata.current();

        schemaChange("CREATE KEYSPACE IF NOT EXISTS " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '3'} " +
                     "AND replication_type = 'tracked'");

        assertSame(before.mutationTrackingShards.keyspaces.get(ks), ClusterMetadata.current().mutationTrackingShards.keyspaces.get(ks));
    }
}
