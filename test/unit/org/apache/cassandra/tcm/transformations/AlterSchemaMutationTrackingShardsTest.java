    private static final AtomicInteger ksCounter = new AtomicInteger();

    @BeforeClass
    public static void setUpClass() throws Exception
    {
        CassandraRelevantProperties.PARTITIONER.setString(Murmur3Partitioner.class.getName());
        ServerTestUtils.daemonInitialization();
        ServerTestUtils.prepareServer();
        MutationJournal.start();

        ClusterMetadata metadata = ClusterMetadata.current();
        Location location = metadata.directory.location(metadata.myNodeId());
        for (int i = 2; i <= 4; i++)
            ClusterMetadataTestHelper.addEndpoint(InetAddressAndPort.getByName("127.0.0." + i), Murmur3Partitioner.instance.getRandomToken(), location);
    }

    private static String localDatacenter()
    {
        ClusterMetadata metadata = ClusterMetadata.current();
        return metadata.directory.location(metadata.myNodeId()).datacenter;
    }

    private static String createKeyspace(String replicationType)
    {
        String ks = "ks_shards_" + ksCounter.incrementAndGet();
        schemaChange("CREATE KEYSPACE " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '3'} " +
                     "AND replication_type = '" + replicationType + '\'');
        return ks;
    }

    private static void assertShardsMatchPlacement(ClusterMetadata metadata, String ks, long expectedEpoch)
    {
        KeyspaceMetadata ksm = metadata.schema.getKeyspaceMetadata(ks);
        ReplicaGroups writes = metadata.placements.get(ksm.params.replication).writes;
        Map<ShardKey, ShardValue> shards = metadata.mutationTrackingShards.keyspaces.get(ks);
        assertNotNull(shards);
        assertEquals(writes.ranges.size(), shards.size());
        for (int i = 0; i < writes.ranges.size(); i++)
        {
            ShardValue shard = shards.get(new ShardKey(writes.ranges.get(i), expectedEpoch));
            assertNotNull("no shard for " + writes.ranges.get(i) + " at epoch " + expectedEpoch, shard);

            Set<Integer> expected = new HashSet<>();
            for (InetAddressAndPort endpoint : writes.endpoints.get(i).endpoints())
                expected.add(metadata.directory.peerId(endpoint).id());
            assertEquals(expected, shard.participants.asSet());
        }
    }

    @Test
    public void trackedKeyspaceGetsShardsAtCreationEpoch()
    {
        String ks = createKeyspace("tracked");
        ClusterMetadata metadata = ClusterMetadata.current();
        assertShardsMatchPlacement(metadata, ks, metadata.epoch.getEpoch());
    }

    @Test
    public void untrackedKeyspaceGetsNoShards()
    {
        String ks = createKeyspace("untracked");
        assertFalse(ClusterMetadata.current().mutationTrackingShards.keyspaces.containsKey(ks));
    }

    @Test
    public void keyspaceSharingPlacementGetsItsOwnEpoch()
    {
        String first = createKeyspace("tracked");
        long firstEpoch = ClusterMetadata.current().epoch.getEpoch();
        String second = createKeyspace("tracked");

        ClusterMetadata metadata = ClusterMetadata.current();
        assertShardsMatchPlacement(metadata, first, firstEpoch);
        assertShardsMatchPlacement(metadata, second, metadata.epoch.getEpoch());
    }

    @Test
    public void createIfNotExistsOnExistingKeyspaceKeepsShards()
    {
        String ks = createKeyspace("tracked");
        ClusterMetadata before = ClusterMetadata.current();

        schemaChange("CREATE KEYSPACE IF NOT EXISTS " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '3'} " +
                     "AND replication_type = 'tracked'");

        assertSame(before.mutationTrackingShards.keyspaces.get(ks), ClusterMetadata.current().mutationTrackingShards.keyspaces.get(ks));
    }

    @Test
    public void dropTrackedKeyspaceRemovesShards()
    {
        String ks = createKeyspace("tracked");
        schemaChange("DROP KEYSPACE " + ks);
        assertFalse(ClusterMetadata.current().mutationTrackingShards.keyspaces.containsKey(ks));
    }

    @Test
    public void dropUntrackedKeyspaceLeavesShardsUnchanged()
    {
        createKeyspace("tracked");
        String untracked = createKeyspace("untracked");
        ClusterMetadata before = ClusterMetadata.current();

        schemaChange("DROP KEYSPACE " + untracked);

        assertEquals(before.mutationTrackingShards.keyspaces, ClusterMetadata.current().mutationTrackingShards.keyspaces);
    }

    @Test
    public void recreatedTrackedKeyspaceGetsShardsAtNewEpoch()
    {
        String ks = createKeyspace("tracked");
        schemaChange("DROP KEYSPACE " + ks);
        schemaChange("CREATE KEYSPACE " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '3'} " +
                     "AND replication_type = 'tracked'");

        ClusterMetadata metadata = ClusterMetadata.current();
        assertShardsMatchPlacement(metadata, ks, metadata.epoch.getEpoch());
    }

    @Test
    public void alterUntrackedToTrackedAddsShardsAtAlterEpoch()
    {
        String ks = createKeyspace("untracked");
        schemaChange("ALTER KEYSPACE " + ks + " WITH replication_type = 'tracked'");

        ClusterMetadata metadata = ClusterMetadata.current();
        assertShardsMatchPlacement(metadata, ks, metadata.epoch.getEpoch());
    }

    @Test
    public void alterTrackedToUntrackedRemovesShards()
    {
        String ks = createKeyspace("tracked");
        schemaChange("ALTER KEYSPACE " + ks + " WITH replication_type = 'untracked'");
        assertFalse(ClusterMetadata.current().mutationTrackingShards.keyspaces.containsKey(ks));
    }

    @Test
    public void alterReplicationOfTrackedKeyspaceChangingParticipantsIsRejected()
    {
        String ks = createKeyspace("tracked");
        ClusterMetadata before = ClusterMetadata.current();
        String message = "Changing replication of a tracked keyspace " + ks + " is currently not supported if it affects the keyspace's write replicas";

        assertThatThrownBy(() -> schemaChange("ALTER KEYSPACE " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '2'}"))
            .hasRootCauseMessage(message);
        assertThatThrownBy(() -> schemaChange("ALTER KEYSPACE " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '4/1'}"))
            .hasRootCauseMessage(message);

        ClusterMetadata after = ClusterMetadata.current();
        assertEquals(before.schema.getKeyspaceMetadata(ks).params, after.schema.getKeyspaceMetadata(ks).params);
        assertSame(before.mutationTrackingShards.keyspaces.get(ks), after.mutationTrackingShards.keyspaces.get(ks));
    }

    @Test
    public void alterTrackedToUntrackedWithReplicationChangeRemovesShards()
    {
        String ks = createKeyspace("tracked");
        schemaChange("ALTER KEYSPACE " + ks + " WITH replication = {'class': 'SimpleStrategy', 'replication_factor': '2'} AND replication_type = 'untracked'");

        ClusterMetadata metadata = ClusterMetadata.current();
        KeyspaceMetadata ksm = metadata.schema.getKeyspaceMetadata(ks);
        assertEquals("2", ksm.params.replication.options.get("replication_factor"));
        assertFalse(ksm.params.replicationType.isTracked());
        assertFalse(metadata.mutationTrackingShards.keyspaces.containsKey(ks));
    }

    @Test
    public void alterReplicationOfTrackedKeyspaceKeepingParticipantsKeepsShards()
    {
        String ks = createKeyspace("tracked");
        Map<ShardKey, ShardValue> before = ClusterMetadata.current().mutationTrackingShards.keyspaces.get(ks);

        schemaChange("ALTER KEYSPACE " + ks + " WITH replication = {'class': 'NetworkTopologyStrategy', '" + localDatacenter() + "': '3'}");

        ClusterMetadata metadata = ClusterMetadata.current();
        assertEquals("NetworkTopologyStrategy", metadata.schema.getKeyspaceMetadata(ks).params.replication.klass.getSimpleName());
        assertSame(before, metadata.mutationTrackingShards.keyspaces.get(ks));
    }

