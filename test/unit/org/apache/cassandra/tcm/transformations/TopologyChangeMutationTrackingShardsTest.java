    private static Map<ShardKey, ShardValue> cancelJoinAt(Transformation.Kind next, long token) throws Exception
    {
        String ks = createTrackedKeyspace(SIMPLE_RF3);
        NodeId joining = register(local.datacenter);

        ClusterMetadata initial = ClusterMetadata.current();
        commit(prepareJoin(joining, token));
        BootstrapAndJoin plan = joinPlan(joining);
        if (next != START_JOIN)
            commit(plan.startJoin);
        if (next == FINISH_JOIN)
            commit(plan.midJoin);
        assertEquals(next, joinPlan(joining).next);

        ClusterMetadata beforeCancel = ClusterMetadata.current();
        ClusterMetadata afterCancel = commit(new CancelInProgressSequence(joining));

        assertEquals("cancellation should restore the original write placements", groups(initial, ks), groups(afterCancel, ks));

        Map<ShardKey, ShardValue> added = assertStepAddsShardsForModifiedGroups(beforeCancel, afterCancel, ks);
        assertFalse(added.isEmpty());
        for (ShardValue shard : added.values())
            assertFalse(shard.participants.asSet().contains(joining.id()));

        // every range whose write replicas changed during the cancelled sequence gets a new shard, rather than
        // reactivating the original one (which may have been sealed)
        Map<Range<Token>, Set<InetAddressAndPort>> beforeGroups = groups(beforeCancel, ks);
        Set<Range<Token>> expectedRanges = new HashSet<>();
        groups(afterCancel, ks).forEach((range, endpoints) -> {
            if (!endpoints.equals(beforeGroups.get(range)))
                expectedRanges.add(range);
        });
        assertEquals(expectedRanges, ranges(added));
        return added;
    }

    @Test
    public void unsafeJoinInDcWithoutTrackedReplicasStillReportsShards() throws Exception
    {
        String ks = createTrackedKeyspace("{'class': 'NetworkTopologyStrategy', '" + local.datacenter + "': '3'}");
        NodeId nodeId = register("remote_dc");
        Set<Token> tokens = ImmutableSet.of(token(2_500_000_000_000_000_000L));
        ClusterMetadata prev = ClusterMetadata.current();

        Transformation.Success steps = unsafeJoinStepsOnly(prev, nodeId, tokens);
        assertFalse("individual steps should not report shard changes when only PrepareJoin split ranges",
                    steps.affectedMetadata.contains(MetadataKeys.MUTATION_TRACKING_SHARDS));
        assertTrue("shards did change relative to prev",
                   MetadataKeys.diffKeys(prev, steps.metadata).contains(MetadataKeys.MUTATION_TRACKING_SHARDS));
        assertEquals("shard lastModified is capped to prev.epoch by forceEpoch()",
                     prev.epoch, steps.metadata.mutationTrackingShards.lastModified);
        assertNotEquals("PrepareJoin split should have created new shards",
                        shards(prev, ks), shards(steps.metadata, ks));

        Transformation.Success result = new UnsafeJoin(nodeId, tokens, ClusterMetadataService.instance().placementProvider()).execute(prev).success();
        assertEquals(prev.nextEpoch(), result.metadata.epoch);
        assertTrue(result.affectedMetadata.contains(MetadataKeys.MUTATION_TRACKING_SHARDS));
        assertTrue(MetadataKeys.diffKeys(prev, result.metadata).contains(MetadataKeys.MUTATION_TRACKING_SHARDS));
        assertEquals(result.metadata.epoch, result.metadata.mutationTrackingShards.lastModified);
        assertEquals("recomputed shard contents match those produced by the steps",
                     steps.metadata.mutationTrackingShards.keyspaces, result.metadata.mutationTrackingShards.keyspaces);

        Map<ShardKey, ShardValue> before = shards(prev, ks);
        Map<ShardKey, ShardValue> after = shards(result.metadata, ks);
        assertEquals(before.size() + 2, after.size());
        long added = after.keySet().stream().filter(k -> k.sinceEpoch == result.metadata.epoch.getEpoch()).count();
        assertEquals(2, added);
    }

    @Test
    public void unsafeJoinInDcWithTrackedReplicasRecomputesShardsAtCommittedEpoch() throws Exception
    {
        String ks = createTrackedKeyspace("{'class': 'NetworkTopologyStrategy', '" + local.datacenter + "': '3'}");
        NodeId nodeId = register(local.datacenter);
        Set<Token> tokens = ImmutableSet.of(token(-2_500_000_000_000_000_000L));
        ClusterMetadata prev = ClusterMetadata.current();

        Transformation.Success steps = unsafeJoinStepsOnly(prev, nodeId, tokens);
        assertTrue(steps.affectedMetadata.contains(MetadataKeys.MUTATION_TRACKING_SHARDS));
        assertTrue("MID_JOIN/FINISH_JOIN leave shards beyond the forced epoch",
                   steps.metadata.mutationTrackingShards.keyspaces.values().stream()
                                                         .anyMatch(s -> s.keySet().stream().anyMatch(k -> k.sinceEpoch > steps.metadata.epoch.getEpoch())));

        Transformation.Success result = new UnsafeJoin(nodeId, tokens, ClusterMetadataService.instance().placementProvider()).execute(prev).success();
        assertTrue(result.affectedMetadata.contains(MetadataKeys.MUTATION_TRACKING_SHARDS));
        assertNotEquals(steps.metadata.mutationTrackingShards.keyspaces, result.metadata.mutationTrackingShards.keyspaces);
        assertEquals(result.metadata.epoch, result.metadata.mutationTrackingShards.lastModified);
        result.metadata.mutationTrackingShards.keyspaces.values().forEach(shards ->
            shards.keySet().forEach(k -> assertTrue(k + " is beyond " + result.metadata.epoch, k.sinceEpoch <= result.metadata.epoch.getEpoch())));

        Map<ShardKey, ShardValue> before = shards(prev, ks);
        Map<ShardKey, ShardValue> after = shards(result.metadata, ks);
        before.forEach((key, value) -> assertEquals("shard " + key + " should be carried forward", value, after.get(key)));

        ReplicaGroups writesBefore = writes(prev, ks);
        Map<ShardKey, Set<Integer>> expected = new HashMap<>();
        writes(result.metadata, ks).forEach((range, endpoints) -> {
            VersionedEndpoints.ForRange previous = writesBefore.forRange(range);
            if (previous == null || !previous.endpoints().equals(endpoints.endpoints()))
                expected.put(new ShardKey(range, result.metadata.epoch.getEpoch()), participants(result.metadata, endpoints));
        });

        Map<ShardKey, Set<Integer>> added = new HashMap<>();
        after.forEach((key, value) -> {
            if (!before.containsKey(key))
                added.put(key, value.participants.asSet());
        });

        assertFalse(expected.isEmpty());
        assertEquals("one shard per new or modified write group, with the final participants and at the committed epoch", expected, added);
        assertTrue("the over-replicated intermediate groups of START_JOIN should not be materialised",
                   added.values().stream().allMatch(participants -> participants.size() == 3));
    }

    private static Transformation.Success unsafeJoinStepsOnly(ClusterMetadata prev, NodeId nodeId, Set<Token> tokens)
    {
        PrepareJoin prepareJoin = new PrepareJoin(nodeId, tokens, ClusterMetadataService.instance().placementProvider(), true, false);
        ClusterMetadata metadata = prepareJoin.execute(prev).success().metadata.forceEpoch(prev.epoch);
        BootstrapAndJoin plan = (BootstrapAndJoin) metadata.inProgressSequences.get(nodeId);
        return plan.applyTo(metadata).success();
    }

