    private static Map<ShardKey, ShardValue> cancelMoveAt(Transformation.Kind next, long from, long to) throws Exception
    {
        String ks = createTrackedKeyspace(SIMPLE_RF3);
        NodeId moving = join(local.datacenter, from);

        ClusterMetadata initial = ClusterMetadata.current();
        commit(prepareMove(moving, to));
        Move plan = movePlan(moving);
        if (next != START_MOVE)
            commit(plan.startMove);
        if (next == FINISH_MOVE)
            commit(plan.midMove);
        assertEquals(next, movePlan(moving).next);

        ClusterMetadata beforeCancel = ClusterMetadata.current();
        ClusterMetadata afterCancel = commit(new CancelInProgressSequence(moving));

        assertEquals("cancellation should restore the original write placements", groups(initial, ks), groups(afterCancel, ks));

        Map<ShardKey, ShardValue> added = assertStepAddsShardsForModifiedGroups(beforeCancel, afterCancel, ks);
        assertFalse(added.isEmpty());
        for (ShardValue shard : added.values())
            assertEquals(3, shard.participants.asSet().size());

        Map<Range<Token>, Set<InetAddressAndPort>> beforeGroups = groups(beforeCancel, ks);
        Set<Range<Token>> expectedRanges = new HashSet<>();
        groups(afterCancel, ks).forEach((range, endpoints) -> {
            if (!endpoints.equals(beforeGroups.get(range)))
                expectedRanges.add(range);
        });
        assertEquals(expectedRanges, ranges(added));
        return added;
    }

    /**
     * Asserts that the step carried forward all pre-existing shards unchanged, and added exactly one shard,
     * at the step's epoch, for every write replica group modified by the step - mirroring the way
     * MutationTrackingService keys its shards by the replica group's lastModified epoch.
     *
     * @return the shards added by the step
     */
    private static Map<ShardKey, ShardValue> assertStepAddsShardsForModifiedGroups(ClusterMetadata before, ClusterMetadata after, String ks)
    {
        assertEquals(before.epoch.nextEpoch(), after.epoch);
        Map<ShardKey, ShardValue> prior = shards(before, ks);
        Map<ShardKey, ShardValue> current = shards(after, ks);

        prior.forEach((key, value) -> assertEquals("shard " + key + " should be carried forward", value, current.get(key)));

        Map<ShardKey, Set<Integer>> added = new HashMap<>();
        Map<ShardKey, ShardValue> addedShards = new HashMap<>();
        current.forEach((key, value) -> {
            if (!prior.containsKey(key))
            {
                added.put(key, value.participants.asSet());
                addedShards.put(key, value);
            }
        });

        long epoch = after.epoch.getEpoch();
        Map<ShardKey, Set<Integer>> expected = new HashMap<>();
        writes(after, ks).forEach((range, endpoints) -> {
            if (endpoints.lastModified().equals(after.epoch))
                expected.put(new ShardKey(range, epoch), participants(after, endpoints));
        });
        assertEquals(expected, added);

        if (!added.isEmpty())
            assertEquals(after.epoch, after.mutationTrackingShards.lastModified);

        assertLatestShardsMatchWrites(after, ks);
        return addedShards;
    }

    /**
     * For every write replica group, the most recent shard over exactly its range must have the group's participants.
     */
    private static void assertLatestShardsMatchWrites(ClusterMetadata metadata, String ks)
    {
        Map<ShardKey, ShardValue> shards = shards(metadata, ks);
        writes(metadata, ks).forEach((range, endpoints) -> {
            ShardKey latest = null;
            for (ShardKey key : shards.keySet())
                if (key.range.equals(range) && (latest == null || key.sinceEpoch > latest.sinceEpoch))
                    latest = key;

            assertNotNull("no shard for write range " + range, latest);
            assertTrue(latest + " predates the last modification of its range at " + endpoints.lastModified(),
                       latest.sinceEpoch >= endpoints.lastModified().getEpoch());
            assertEquals(participants(metadata, endpoints), shards.get(latest).participants.asSet());
        });
    }

    /**
     * PREPARE_JOIN splits exactly one range in two, with both halves inheriting the original participants,
     * which cannot include the joining node.
     */
    private static void assertSplitShards(ClusterMetadata before, Map<ShardKey, ShardValue> split, String ks, NodeId joining)
    {
        for (ShardValue shard : split.values())
            assertFalse(shard.participants.asSet().contains(joining.id()));
        assertSplitShards(before, split, ks);
    }

    /**
     * PREPARE_JOIN and PREPARE_MOVE split exactly one range in two, with both halves inheriting the original participants.
     */
    private static void assertSplitShards(ClusterMetadata before, Map<ShardKey, ShardValue> split, String ks)
    {
        assertEquals(2, split.size());
        Set<Integer> participants = null;
        Range<Token> union = null;
        for (Map.Entry<ShardKey, ShardValue> entry : split.entrySet())
        {
            Set<Integer> shardParticipants = entry.getValue().participants.asSet();
            if (participants == null)
                participants = shardParticipants;
            else
                assertEquals(participants, shardParticipants);

            Range<Token> range = entry.getKey().range;
            union = union == null ? range : (union.right.equals(range.left) ? new Range<>(union.left, range.right) : new Range<>(range.left, union.right));
        }

        VersionedEndpoints.ForRange parent = writes(before, ks).forRange(union);
        assertNotNull("split ranges should form a pre-existing range, but got " + union, parent);
        assertEquals(participants(before, parent), participants);
    }

    /**
     * FINISH_LEAVE and FINISH_MOVE merge the node's (old) range with its successor's: the merged range must not
     * have existed before the step, and must get a shard of its own.
     */
    private static void assertMergedRangeHasShard(ClusterMetadata before, ClusterMetadata after, Map<ShardKey, ShardValue> added, String ks, NodeId node)
    {
        Token oldToken = before.tokenMap.tokens(node).iterator().next();
        Range<Token> merged = null;
        for (Range<Token> range : writes(after, ks).ranges)
            if (range.contains(oldToken) && !range.right.equals(oldToken))
                merged = range;

        assertNotNull("no merged range containing " + oldToken, merged);
        assertNull("merged range " + merged + " should not have existed before the merge", writes(before, ks).forRange(merged));
        assertTrue("no shard for merged range " + merged, ranges(added).contains(merged));
    }

