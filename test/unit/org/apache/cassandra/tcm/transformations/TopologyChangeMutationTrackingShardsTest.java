    private static Map<Range<Token>, Set<InetAddressAndPort>> groups(ClusterMetadata metadata, String ks)
    {
        Map<Range<Token>, Set<InetAddressAndPort>> groups = new HashMap<>();
        writes(metadata, ks).forEach((range, endpoints) -> groups.put(range, endpoints.endpoints()));
        return groups;
    }

    private static Set<Integer> participants(ClusterMetadata metadata, VersionedEndpoints.ForRange endpoints)
    {
        Set<Integer> ids = new HashSet<>();
        for (InetAddressAndPort endpoint : endpoints.endpoints())
            ids.add(metadata.directory.peerId(endpoint).id());
        return ids;
    }

    private static Set<Range<Token>> ranges(Map<ShardKey, ShardValue> shards)
    {
        Set<Range<Token>> ranges = new HashSet<>();
        for (ShardKey key : shards.keySet())
            ranges.add(key.range);
        return ranges;
    }
