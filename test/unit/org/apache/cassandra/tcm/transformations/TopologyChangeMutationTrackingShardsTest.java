    @Test
    public void bootstrapAddsShardsAtEachWriteChangingStep() throws Exception
    {
        String ks = createTrackedKeyspace(SIMPLE_RF3);
        NodeId joining = register(local.datacenter);

        ClusterMetadata initial = ClusterMetadata.current();
        ClusterMetadata afterPrepare = commit(prepareJoin(joining, 1_000_000_000_000_000_000L));
        Map<ShardKey, ShardValue> split = assertStepAddsShardsForModifiedGroups(initial, afterPrepare, ks);
        assertSplitShards(initial, split, ks, joining);

        BootstrapAndJoin plan = joinPlan(joining);

        ClusterMetadata afterStart = commit(plan.startJoin);
        Map<ShardKey, ShardValue> started = assertStepAddsShardsForModifiedGroups(afterPrepare, afterStart, ks);
        assertFalse(started.isEmpty());
        for (ShardValue shard : started.values())
        {
            assertTrue(shard.participants.asSet().contains(joining.id()));
            assertEquals("START_JOIN shards are over-replicated", 4, shard.participants.asSet().size());
        }

        ClusterMetadata afterMid = commit(plan.midJoin);
        assertSame("MID_JOIN only changes read placements", shards(afterStart, ks), shards(afterMid, ks));

        ClusterMetadata afterFinish = commit(plan.finishJoin);
        Map<ShardKey, ShardValue> finished = assertStepAddsShardsForModifiedGroups(afterMid, afterFinish, ks);
        assertEquals("FINISH_JOIN should supersede exactly the over-replicated ranges", ranges(started), ranges(finished));
        for (ShardValue shard : finished.values())
        {
            assertTrue(shard.participants.asSet().contains(joining.id()));
            assertEquals(3, shard.participants.asSet().size());
        }

        ClusterMetadata afterRetire = retire(joining, plan.lockKey);
        assertSame("RETIRE_SINGLE_NODE_SEQUENCE must not change shards", shards(afterFinish, ks), shards(afterRetire, ks));
    }

