    @Test
    public void assassinateAddsShardsAtCommittedEpochOnly() throws Exception
    {
        String ks = createTrackedKeyspace(SIMPLE_RF3);
        NodeId leaving = join(local.datacenter, 7_000_000_000_000_000_000L);

        ClusterMetadata prev = ClusterMetadata.current();
        Transformation.Success result = new Assassinate(leaving, ClusterMetadataService.instance().placementProvider()).execute(prev).success();
        assertEquals(prev.nextEpoch(), result.metadata.epoch);
        assertTrue(result.affectedMetadata.contains(MetadataKeys.MUTATION_TRACKING_SHARDS));
        assertEquals(result.metadata.epoch, result.metadata.mutationTrackingShards.lastModified);

        Map<ShardKey, ShardValue> before = shards(prev, ks);
        Map<ShardKey, ShardValue> after = shards(result.metadata, ks);
        before.forEach((key, value) -> assertEquals("shard " + key + " should be carried forward", value, after.get(key)));

        ReplicaGroups writesBefore = writes(prev, ks);
        Map<ShardKey, Set<Integer>> expected = new HashMap<>();
        writes(result.metadata, ks).forEach((range, endpoints) -> {
            VersionedEndpoints.ForRange previous = writesBefore.forRange(range);
            if (previous == null || !previous.endpoints().equals(endpoints.endpoints()))
                expected.put(new ShardKey(range, result.metadata.epoch.getEpoch()), participants(result.metadata, endpoints));
        });

        Map<ShardKey, Set<Integer>> added = new HashMap<>();
        after.forEach((key, value) -> {
            if (!before.containsKey(key))
                added.put(key, value.participants.asSet());
        });

        assertFalse(expected.isEmpty());
        assertEquals("one shard per new or modified write group, with the final participants and at the committed epoch", expected, added);
        assertTrue("the over-replicated intermediate groups of START_LEAVE should not be materialised",
                   added.values().stream().allMatch(participants -> participants.size() == 3 && !participants.contains(leaving.id())));

        ClusterMetadata committed = commit(new Assassinate(leaving, ClusterMetadataService.instance().placementProvider()));
        assertNull(committed.inProgressSequences.get(leaving));
        assertLatestShardsMatchWrites(committed, ks);
    }

    @Test
    public void moveAddsShardsAtEachWriteChangingStep() throws Exception
    {
        String ks = createTrackedKeyspace(SIMPLE_RF3);
        NodeId moving = join(local.datacenter, 2_750_000_000_000_000_000L);

        ClusterMetadata initial = ClusterMetadata.current();
        ClusterMetadata afterPrepare = commit(prepareMove(moving, -2_750_000_000_000_000_000L));
        Map<ShardKey, ShardValue> split = assertStepAddsShardsForModifiedGroups(initial, afterPrepare, ks);
        assertSplitShards(initial, split, ks);

        Move plan = movePlan(moving);

        ClusterMetadata afterStart = commit(plan.startMove);
        Map<ShardKey, ShardValue> started = assertStepAddsShardsForModifiedGroups(afterPrepare, afterStart, ks);
        assertFalse(started.isEmpty());
        for (ShardValue shard : started.values())
        {
            assertTrue(shard.participants.asSet().contains(moving.id()));
            assertEquals("START_MOVE shards are over-replicated", 4, shard.participants.asSet().size());
        }

        ClusterMetadata afterMid = commit(plan.midMove);
        assertSame("MID_MOVE only changes read placements", shards(afterStart, ks), shards(afterMid, ks));

        ClusterMetadata afterFinish = commit(plan.finishMove);
        Map<ShardKey, ShardValue> finished = assertStepAddsShardsForModifiedGroups(afterMid, afterFinish, ks);
        assertFalse(finished.isEmpty());
        for (ShardValue shard : finished.values())
            assertEquals(3, shard.participants.asSet().size());
        assertMergedRangeHasShard(afterMid, afterFinish, finished, ks, moving);

        ClusterMetadata afterRetire = retire(moving, plan.lockKey);
        assertSame("RETIRE_SINGLE_NODE_SEQUENCE must not change shards", shards(afterFinish, ks), shards(afterRetire, ks));
    }

