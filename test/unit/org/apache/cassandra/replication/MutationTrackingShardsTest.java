package org.apache.cassandra.replication;

import java.util.HashSet;
import java.util.Set;

import com.google.common.collect.ImmutableMap;
import com.google.common.collect.ImmutableSet;
import org.junit.Test;

import org.apache.cassandra.dht.Murmur3Partitioner.LongToken;
import org.apache.cassandra.dht.Range;
import org.apache.cassandra.dht.Token;
import org.apache.cassandra.replication.MutationTrackingShards.ShardKey;
import org.apache.cassandra.replication.MutationTrackingShards.ShardValue;
import org.apache.cassandra.tcm.Epoch;

import static org.apache.cassandra.replication.MutationTrackingShards.ShardValue.State.DISABLED;
import static org.apache.cassandra.replication.MutationTrackingShards.ShardValue.State.SEALED;
import static org.apache.cassandra.replication.MutationTrackingShards.ShardValue.State.SEALING;
import static org.junit.Assert.assertEquals;

/**
 * Tests generated by an LLM and only skimmed by me (AY).
 * Feel free to get rid of them / rewrite them if they get in the way.
 */
public class MutationTrackingShardsTest
{
    @Test
    public void markedSealingAt()
    {
        MutationTrackingShards shards = new MutationTrackingShards(Epoch.create(5), ImmutableMap.of(
            "ks1", ImmutableMap.of(key(10, 20, 1), new ShardValue(SEALING, 3, participants(1, 2, 3)),
                                   key(20, 30, 1), new ShardValue(SEALING, 4, participants(1, 2, 3)),
                                   key(30, 40, 1), new ShardValue(SEALED, 3, participants(1, 2, 3)),
                                   key(40, 50, 1), new ShardValue(DISABLED, ShardValue.UNSET, participants(1, 2, 3)),
                                   key(10, 20, 3), new ShardValue(participants(1, 2, 4))),
            "ks2", ImmutableMap.of(key(10, 20, 2), new ShardValue(SEALING, 3, participants(4, 5, 6)),
                                   key(10, 20, 3), new ShardValue(participants(4, 5, 7)))));

        Set<ShardMetadata> sealing = shards.markedSealingAt(Epoch.create(3));
        assertEquals(ImmutableSet.of(new ShardMetadata("ks1", 1, range(10, 20), participants(1, 2, 3)),
                                     new ShardMetadata("ks2", 2, range(10, 20), participants(4, 5, 6))),
                     sealing);

        assertEquals(ImmutableSet.of(key(20, 30, 1)), keys(shards.markedSealingAt(Epoch.create(4)), "ks1"));
        assertEquals(ImmutableSet.of(), shards.markedSealingAt(Epoch.create(5)));
    }

    public static Set<ShardKey> keys(Set<ShardMetadata> shards, String keyspace)
    {
        Set<ShardKey> keys = new HashSet<>();
        for (ShardMetadata shard : shards)
            if (shard.keyspace.equals(keyspace))
                keys.add(new ShardKey(shard.range, shard.sinceEpoch));
        return keys;
    }

    private static ShardKey key(long left, long right, long sinceEpoch)
    {
        return new ShardKey(range(left, right), sinceEpoch);
    }

    private static Range<Token> range(long left, long right)
    {
        return new Range<>(new LongToken(left), new LongToken(right));
    }

    private static Participants participants(int... hosts)
    {
        return new Participants(hosts);
    }
}
