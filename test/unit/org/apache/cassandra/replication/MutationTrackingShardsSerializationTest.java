package org.apache.cassandra.replication;

import java.io.IOException;

import com.google.common.collect.ImmutableMap;
import org.junit.BeforeClass;
import org.junit.Test;

import org.apache.cassandra.config.DatabaseDescriptor;
import org.apache.cassandra.dht.IPartitioner;
import org.apache.cassandra.dht.Murmur3Partitioner;
import org.apache.cassandra.dht.Range;
import org.apache.cassandra.dht.Token;
import org.apache.cassandra.io.util.DataInputBuffer;
import org.apache.cassandra.io.util.DataOutputBuffer;
import org.apache.cassandra.replication.MutationTrackingShards.ShardKey;
import org.apache.cassandra.replication.MutationTrackingShards.ShardValue;
import org.apache.cassandra.replication.MutationTrackingShards.ShardValue.State;
import org.apache.cassandra.tcm.Epoch;
import org.apache.cassandra.tcm.serialization.Version;

import static org.apache.cassandra.tcm.serialization.Version.MIN_MUTATION_TRACKING_SHARDS_VERSION;
import static org.junit.Assert.assertEquals;

/**
 * Tests generated by an LLM and only skimmed by me (AY).
 * Feel free to get rid of them / rewrite them if they get in the way.
 */
public class MutationTrackingShardsSerializationTest
{
    private static final IPartitioner partitioner = Murmur3Partitioner.instance;

    @BeforeClass
    public static void setUpClass()
    {
        DatabaseDescriptor.clientInitialization();
    }

    @Test
    public void testEmpty() throws IOException
    {
        roundtrip(MutationTrackingShards.EMPTY);
    }

    @Test
    public void testAllStates() throws IOException
    {
        ImmutableMap<ShardKey, ShardValue> ks1 = ImmutableMap.of(
            key(-100, 0, 3),           new ShardValue(State.SEALED, 9, participants(1, 2, 3)),
            key(-100, 0, 9),           new ShardValue(State.SEALING, 1_000_000, participants(1, 2, 4)),
            key(-100, 0, 1_000_000),   new ShardValue(participants(1, 4, 5)),
            key(0, Long.MIN_VALUE, 3), new ShardValue(participants(2, 3, 4)));
        ImmutableMap<ShardKey, ShardValue> ks2 = ImmutableMap.of(
            key(Long.MIN_VALUE, Long.MIN_VALUE, 7), new ShardValue(participants(1)),
            key(Long.MIN_VALUE, Long.MIN_VALUE, 5), new ShardValue(State.DISABLED, ShardValue.UNSET, participants(1, 2)));

        roundtrip(new MutationTrackingShards(Epoch.create(1_000_000), ImmutableMap.of("ks1", ks1, "ks2", ks2)));
    }

    private static void roundtrip(MutationTrackingShards shards) throws IOException
    {
        for (Version version : Version.values())
        {
            if (!version.isAtLeast(MIN_MUTATION_TRACKING_SHARDS_VERSION) || version == Version.UNKNOWN)
                continue;

            try (DataOutputBuffer out = new DataOutputBuffer())
            {
                MutationTrackingShards.serializer.serialize(shards, out, partitioner, version);
                assertEquals(MutationTrackingShards.serializer.serializedSize(shards, partitioner, version), out.getLength());

                try (DataInputBuffer in = new DataInputBuffer(out.toByteArray()))
                {
                    MutationTrackingShards deserialized = MutationTrackingShards.serializer.deserialize(in, partitioner, version);
                    assertEquals(shards, deserialized);
                    assertEquals(0, in.available());
                }
            }
        }
    }

    private static ShardKey key(long left, long right, long sinceEpoch)
    {
        return new ShardKey(new Range<>(token(left), token(right)), sinceEpoch);
    }

    private static Token token(long token)
    {
        return new Murmur3Partitioner.LongToken(token);
    }

    private static Participants participants(int... hosts)
    {
        return new Participants(hosts);
    }
}
